import { createHash } from "node:crypto";
import {
  existsSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const supportRoot = join(projectRoot, "ios", "Pods", "Target Support Files");
const noticePath = join(projectRoot, "THIRD_PARTY_NOTICES.txt");
const sourcePath = join(projectRoot, "src", "thirdPartyNotices.ts");
const marker = "iOS CocoaPods acknowledgements (generated from Podfile.lock)";

function findAcknowledgements(directory) {
  if (!existsSync(directory)) return [];
  const matches = [];
  for (const name of readdirSync(directory)) {
    const path = join(directory, name);
    if (statSync(path).isDirectory()) {
      matches.push(...findAcknowledgements(path));
    } else if (name.endsWith("-acknowledgements.markdown")) {
      matches.push(path);
    }
  }
  return matches;
}

const allAcknowledgements = findAcknowledgements(supportRoot);
const appAcknowledgements = allAcknowledgements.filter((path) =>
  path.endsWith(
    "/Pods-SNAPEBTGroceryTrackerQA-acknowledgements.markdown",
  ),
);

if (appAcknowledgements.length !== 1) {
  throw new Error(
    `Expected one application CocoaPods acknowledgement file; found ${appAcknowledgements.length}.`,
  );
}
if (!existsSync(noticePath)) {
  throw new Error("Generate the npm third-party notices before finalizing iOS notices.");
}

const nativeNotices = readFileSync(appAcknowledgements[0], "utf8").trim();
for (const component of ["openiap"]) {
  if (!nativeNotices.toLowerCase().includes(component.toLowerCase())) {
    throw new Error(`CocoaPods acknowledgements are missing ${component}.`);
  }
}

const npmNotices = readFileSync(noticePath, "utf8")
  .split(`\n\n${marker}\n`, 1)[0]
  .trimEnd();
if (!npmNotices.includes("expo-iap@5.2.4")) {
  throw new Error("The npm third-party notices are missing expo-iap@5.2.4.");
}
if (!npmNotices.includes("expo-tracking-transparency@57.0.1")) {
  throw new Error("The npm third-party notices are missing expo-tracking-transparency@57.0.1.");
}

const combinedNotices = `${npmNotices}\n\n${marker}\n\n${nativeNotices}\n`;
writeFileSync(noticePath, combinedNotices);
writeFileSync(
  sourcePath,
  `// Generated by scripts/generate-notices.mjs and scripts/finalize-ios-notices.mjs. Do not edit by hand.\n` +
    `export const THIRD_PARTY_NOTICES = ${JSON.stringify(combinedNotices)};\n`,
);

const digest = createHash("sha256").update(combinedNotices).digest("hex");
console.log(
  `Finalized iOS notices from ${appAcknowledgements[0]} (SHA-256 ${digest}).`,
);
